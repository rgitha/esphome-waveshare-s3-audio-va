#!/usr/bin/env bash
# Patches for the local copies of ESPHome components (components/<name>).
#
#   patches/regen.sh diff
#       Rewrite patches/<name>.patch from components/<name> against the ESPHome
#       version in patches/BASE. Run after every change to a copy, in the same commit.
#
#   patches/regen.sh apply <version>        e.g. patches/regen.sh apply 2026.12.0
#       Rebuild components/<name> for ESPHome <version>: our changes (BASE -> patch)
#       are merged onto <version> with a three-way merge. Conflicts are left in the
#       files as <<<<<<< ======= >>>>>>> markers and listed at the end. When all
#       components are clean (or fixed by hand), set patches/BASE to <version> and run
#       "patches/regen.sh diff".
#
# Needs bash and git. Fetches the components from esphome/esphome on GitHub (by tag).
set -euo pipefail

COMPONENTS=(voice_assistant micro_wake_word)
HERE="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
REPO="$(dirname "$HERE")"
BASE="$(tr -d '[:space:]' < "$HERE/BASE")"
WORK="$(mktemp -d)"
trap 'rm -rf "$WORK"' EXIT

fetch() {  # fetch <version> -> $WORK/esphome-<version>/esphome/components (only our components)
  local v="$1"
  local d="$WORK/esphome-$v"
  if [ ! -d "$d" ]; then
    echo "Fetching ESPHome $v ..." >&2
    git -c advice.detachedHead=false clone -q --depth 1 --branch "$v" --filter=blob:none --sparse https://github.com/esphome/esphome.git "$d" 2>&1 |
      grep -v "^warning" >&2 || true
    local paths=()
    for c in "${COMPONENTS[@]}"; do paths+=("esphome/components/$c"); done
    git -C "$d" sparse-checkout set "${paths[@]}" >&2
  fi
  echo "$d/esphome/components"
}

cmd_diff() {
  local up
  up="$(fetch "$BASE")"
  for c in "${COMPONENTS[@]}"; do
    local a="$WORK/a/components/$c" b="$WORK/b/components/$c"
    mkdir -p "$a" "$b"
    cp -R "$up/$c/." "$a/"
    cp -R "$REPO/components/$c/." "$b/"
    find "$WORK/a" "$WORK/b" -name __pycache__ -prune -exec rm -rf {} +
    {
      echo "# Local changes to ESPHome's $c component, against ESPHome $BASE."
      echo "# Generated by patches/regen.sh diff; do not edit by hand."
      (cd "$WORK" && git diff --no-index --no-prefix --binary "a/components/$c" "b/components/$c") || true
    } > "$HERE/$c.patch"
    echo "$c: $(grep -c '^[-+][^-+]' "$HERE/$c.patch") changed lines -> patches/$c.patch"
  done
}

cmd_apply() {
  local target="$1" base_up target_up conflicts=()
  base_up="$(fetch "$BASE")"
  target_up="$(fetch "$target")"
  for c in "${COMPONENTS[@]}"; do
    local g="$WORK/git-$c"
    mkdir -p "$g" && cd "$g"
    git init -q && git config user.email regen@local && git config user.name regen
    # base -> ours (base + our patch)
    mkdir -p "components/$c" && cp -R "$base_up/$c/." "components/$c/"
    git add -A && git commit -qm "ESPHome $BASE"
    if ! git apply --index -p1 "$HERE/$c.patch" 2>/dev/null; then
      echo "$c: patches/$c.patch does not apply to ESPHome $BASE (stale patch?)" >&2
      exit 1
    fi
    git commit -qm "ours"
    local ours
    ours="$(git rev-parse HEAD)"
    # base -> upstream target
    git checkout -q -b upstream HEAD~1
    rm -rf "components/$c" && mkdir -p "components/$c"
    if [ -d "$target_up/$c" ]; then cp -R "$target_up/$c/." "components/$c/"; fi
    git add -A && git commit -qm "ESPHome $target" --allow-empty
    # our changes onto the target
    if git cherry-pick "$ours" >/dev/null 2>&1; then
      echo "$c: merged cleanly onto ESPHome $target"
    else
      mapfile -t files < <(git diff --name-only --diff-filter=U)
      if [ "${#files[@]}" -eq 0 ] && git diff --cached --quiet; then
        echo "$c: our changes are already in ESPHome $target (patch now empty: drop this copy?)"
        git cherry-pick --skip >/dev/null 2>&1 || true
      else
        echo "$c: CONFLICTS in: ${files[*]}"
        conflicts+=("$c")
      fi
    fi
    rm -rf "$REPO/components/$c" && mkdir -p "$REPO/components/$c"
    cp -R "components/$c/." "$REPO/components/$c/"
    cd "$REPO"
  done
  echo
  if [ "${#conflicts[@]}" -eq 0 ]; then
    echo "Done. Build and test, then: echo $target > patches/BASE && patches/regen.sh diff"
  else
    echo "Fix the conflict markers in: ${conflicts[*]}; then build, test, set patches/BASE to $target and run diff."
  fi
}

case "${1:-}" in
  diff) cmd_diff ;;
  apply) [ -n "${2:-}" ] || { echo "usage: $0 apply <esphome-version>" >&2; exit 2; }; cmd_apply "$2" ;;
  *) sed -n '2,17p' "$0"; exit 2 ;;
esac
