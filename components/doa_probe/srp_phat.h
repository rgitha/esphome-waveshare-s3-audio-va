#pragma once

// Two-microphone SRP-PHAT direction of arrival (steered response power with the
// phase transform). Plain C++, no allocation after init(); the caller supplies the
// allocator so the buffers can go to PSRAM.
//
// Angle convention: 0 deg = source on the side of the "near" mic (it hears it first),
// 90 deg = broadside (straight ahead or behind), 180 deg = the "far" mic's side.
// Two mics cannot tell front from back.

#include <algorithm>
#include <cmath>
#include <cstddef>
#include <cstdint>

namespace esphome::doa_probe {

class SrpPhat {
 public:
  using AllocFn = void *(*) (size_t bytes);

  // n: frame length (power of two), fs: sample rate, d: (effective) mic distance (m),
  // resolution: angle step (deg), f_lo/f_hi: band used (Hz), delay_offset: fixed extra
  // delay of the far mic (s), for calibration (channel timing or phase mismatch).
  bool init(int n, float fs, float d, float resolution, float f_lo, float f_hi, AllocFn alloc,
            float delay_offset = 0.0f) {
    if (n < 64 || (n & (n - 1)) != 0 || d <= 0 || resolution <= 0)
      return false;
    n_ = n;
    log2n_ = 0;
    while ((1 << log2n_) < n)
      log2n_++;
    re_ = static_cast<float *>(alloc(sizeof(float) * n));
    im_ = static_cast<float *>(alloc(sizeof(float) * n));
    win_ = static_cast<float *>(alloc(sizeof(float) * n));
    tw_cos_ = static_cast<float *>(alloc(sizeof(float) * (n / 2)));
    tw_sin_ = static_cast<float *>(alloc(sizeof(float) * (n / 2)));
    rev_ = static_cast<uint16_t *>(alloc(sizeof(uint16_t) * n));
    num_angles_ = static_cast<int>(180.0f / resolution) + 1;
    resolution_ = 180.0f / (num_angles_ - 1);
    k_lo_ = std::max(1, static_cast<int>(std::ceil(f_lo * n / fs)));
    k_hi_ = std::min(n / 2 - 1, static_cast<int>(std::floor(f_hi * n / fs)));
    const int bins = k_hi_ - k_lo_ + 1;
    g_re_ = static_cast<float *>(alloc(sizeof(float) * bins));
    g_im_ = static_cast<float *>(alloc(sizeof(float) * bins));
    rot_cos_ = static_cast<float *>(alloc(sizeof(float) * num_angles_));
    rot_sin_ = static_cast<float *>(alloc(sizeof(float) * num_angles_));
    start_cos_ = static_cast<float *>(alloc(sizeof(float) * num_angles_));
    start_sin_ = static_cast<float *>(alloc(sizeof(float) * num_angles_));
    power_ = static_cast<float *>(alloc(sizeof(float) * num_angles_));
    if (!re_ || !im_ || !win_ || !tw_cos_ || !tw_sin_ || !rev_ || !g_re_ || !g_im_ || !rot_cos_ || !rot_sin_ ||
        !start_cos_ || !start_sin_ || !power_ || bins < 2)
      return false;
    const float pi = 3.14159265358979f;
    for (int i = 0; i < n; i++) {
      win_[i] = 0.5f - 0.5f * std::cos(2 * pi * i / n);  // Hann
      int r = 0;
      for (int b = 0; b < log2n_; b++)
        if (i & (1 << b))
          r |= 1 << (log2n_ - 1 - b);
      rev_[i] = static_cast<uint16_t>(r);
    }
    for (int i = 0; i < n / 2; i++) {
      tw_cos_[i] = std::cos(2 * pi * i / n);
      tw_sin_[i] = -std::sin(2 * pi * i / n);
    }
    // Steering: for angle a, the far mic hears the source tau = d cos(a) / c (+ the
    // calibration offset) later.
    // Bin k: phase step w_k tau, w_k = 2 pi k fs / n; generated by rotation from k_lo.
    const float c = 343.0f;
    for (int a = 0; a < num_angles_; a++) {
      const float tau = d * std::cos(a * resolution_ * pi / 180.0f) / c + delay_offset;
      const float step = 2 * pi * fs / n * tau;
      rot_cos_[a] = std::cos(step);
      rot_sin_[a] = std::sin(step);
      start_cos_[a] = std::cos(step * k_lo_);
      start_sin_[a] = std::sin(step * k_lo_);
    }
    ready_ = true;
    return true;
  }

  int k_lo() const { return k_lo_; }
  int k_hi() const { return k_hi_; }
  int num_angles() const { return num_angles_; }

  // near/far: one frame of n samples from each mic. Returns the angle (deg), or a
  // negative value if the frame has no usable signal.
  float process(const int16_t *near_mic, const int16_t *far_mic) {
    if (!ready_)
      return -1;
    const int n = n_;
    // Both real signals in one complex FFT: z = near + j far.
    for (int i = 0; i < n; i++) {
      re_[rev_[i]] = near_mic[i] * win_[i];
      im_[rev_[i]] = far_mic[i] * win_[i];
    }
    fft_();
    // X (near), Y (far) from Z: X[k] = (Z[k] + conj Z[n-k]) / 2, Y[k] = (Z[k] - conj Z[n-k]) / 2j
    // PHAT-weighted cross spectrum G = X conj(Y) / |X conj(Y)|. The far mic is delayed,
    // so G = |.| e^{+j w tau0}.
    int bins = 0;
    for (int k = k_lo_; k <= k_hi_; k++, bins++) {
      const float zr = re_[k], zi = im_[k], wr = re_[n - k], wi = -im_[n - k];  // w = conj Z[n-k]
      const float xr = 0.5f * (zr + wr), xi = 0.5f * (zi + wi);
      const float yr = 0.5f * (zi - wi), yi = -0.5f * (zr - wr);
      float gr = xr * yr + xi * yi;  // X * conj(Y)
      float gi = xi * yr - xr * yi;
      const float mag = std::sqrt(gr * gr + gi * gi);
      if (mag > 1e-9f) {
        gr /= mag;
        gi /= mag;
      } else {
        gr = gi = 0;
      }
      g_re_[bins] = gr;
      g_im_[bins] = gi;
    }
    // P(a) = sum_k Re(G[k] e^{-j w_k tau(a)})
    int best = 0;
    for (int a = 0; a < num_angles_; a++) {
      float sc = start_cos_[a], ss = start_sin_[a];
      const float rc = rot_cos_[a], rs = rot_sin_[a];
      float p = 0;
      for (int b = 0; b < bins; b++) {
        p += g_re_[b] * sc + g_im_[b] * ss;  // Re(G e^{-j phi}) = gr cos + gi sin
        const float t = sc * rc - ss * rs;
        ss = ss * rc + sc * rs;
        sc = t;
      }
      power_[a] = p;
      if (p > power_[best])
        best = a;
    }
    float angle = best * resolution_;
    if (best > 0 && best < num_angles_ - 1) {  // parabolic refinement
      const float l = power_[best - 1], m = power_[best], r = power_[best + 1];
      const float den = l - 2 * m + r;
      if (den < 0)
        angle += 0.5f * (l - r) / den * resolution_;
    }
    return angle;
  }

 protected:
  void fft_() {
    const int n = n_;
    for (int len = 2; len <= n; len <<= 1) {
      const int half = len >> 1, step = n / len;
      for (int i = 0; i < n; i += len) {
        for (int j = 0; j < half; j++) {
          const float c = tw_cos_[j * step], s = tw_sin_[j * step];
          const int u = i + j, v = u + half;
          const float tr = re_[v] * c - im_[v] * s, ti = re_[v] * s + im_[v] * c;
          re_[v] = re_[u] - tr;
          im_[v] = im_[u] - ti;
          re_[u] += tr;
          im_[u] += ti;
        }
      }
    }
  }

  bool ready_{false};
  int n_{0}, log2n_{0}, num_angles_{0}, k_lo_{0}, k_hi_{0};
  float resolution_{1};
  float *re_{nullptr}, *im_{nullptr}, *win_{nullptr}, *tw_cos_{nullptr}, *tw_sin_{nullptr};
  uint16_t *rev_{nullptr};
  float *g_re_{nullptr}, *g_im_{nullptr};
  float *rot_cos_{nullptr}, *rot_sin_{nullptr}, *start_cos_{nullptr}, *start_sin_{nullptr}, *power_{nullptr};
};

}  // namespace esphome::doa_probe
